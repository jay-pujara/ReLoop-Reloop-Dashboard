/** Flat list of land dots in grid units. */
export const LAND_DOTS = LAND.flatMap((ranges, row) =>
  ranges.flatMap(([from, to]) => {
    const dots = [];
    for (let col = from; col <= to; col += 1) {
      dots.push({ x: col, y: row, col, row });
    }
    return dots;
  }),
);

